#!/usr/bin/env python3
"""Why is SWMM6 so big?  Count source lines in EPA 5.2.4, swmm5-cplus and SWMM6, and sort SWMM6's
engine files into five purpose buckets by path.  Writes docs/swmm6_loc.json for the essay figures.

    python3 tools/loc_buckets.py EPA_TAG_DIR SWMM5CPLUS_DIR OPENSWMM_DIR [SWMM6_COMMIT] > docs/swmm6_loc.json

EPA_TAG_DIR    a checkout of USEPA/Stormwater-Management-Model at tag v5.2.4
SWMM5CPLUS_DIR this repository
OPENSWMM_DIR   a checkout of HydroCouple/openswmm.engine (branch swmm6_rel)

Counting rules (deliberately simple, the same for all three engines):
  files       .c .cpp .h .hpp
  blank       a line that is empty after stripping
  comment     a line that starts with //, /*, or *, or lies inside a /* ... */ block
  code        everything else (so a code line with a trailing comment counts as code)
Buckets are assigned by file path, first matching rule wins; see RULES.  They are approximate.
"""
import os, re, sys, json, collections

EXTS = {'.c', '.cpp', '.h', '.hpp'}

def count(path):
    t = b = c = 0
    inblock = False
    for line in open(path, errors='replace'):
        t += 1
        s = line.strip()
        if not s:
            b += 1
            continue
        if inblock:
            c += 1
            if '*/' in s:
                inblock = False
            continue
        if s.startswith('//') or s.startswith('*'):
            c += 1
            continue
        if s.startswith('/*'):
            c += 1
            if '*/' not in s:
                inblock = True
    return t, b, c

def files(root, skip=()):
    for d, dirs, fs in os.walk(root):
        dirs[:] = sorted(x for x in dirs if os.path.relpath(os.path.join(d, x), root) not in skip)
        for f in sorted(fs):
            if os.path.splitext(f)[1] in EXTS:
                yield os.path.join(d, f)

def tally(paths):
    n = t = b = c = 0
    for p in paths:
        a = count(p)
        n += 1; t += a[0]; b += a[1]; c += a[2]
    return dict(files=n, lines=t, blank=b, comment=c, code=t - b - c)

# first match wins; paths are relative to openswmm.engine/src/engine
RULES = [
    ('saverestore', 'Save/restore, live editing, file interchange',
     r'(Checkpoint|HotStart|InpWriter|geopackage/|InterfaceFile|^edit/|AtomicOutputFile|'
     r'CompletedSourceArchive|NativeModelBundle|CheckpointInspection)'),
    ('api', 'Public API implementation',
     r'(core/openswmm_|EngineAbi|api_common)'),
    ('newphysics', 'New physics that 5.2.4 does not have',
     r'(hydraulics/fv/|quality/lard/|FlowTracer|^transport/|Ueb|MeshSnow|SourceSnow|NativeSnow|InfilBank|'
     r'Richards|LidNode|SourceWater|SourceClock|Radiation|SolarGeometry|HourlyMeteorology|Heat|heat|'
     r'Reaction|Msx|WaterAge|BedZone|Species|ArdConfig|NodeCoupling2D|ChannelThermal|'
     r'AquiferLinkExchange|SurfaceExchange)'),
    ('infra', 'Plugins, threads, timers, errors, paths',
     r'(^plugins/(?!DefaultReport)|^io/|ErrorCodes|PathResolver|ThreadInfo|PerfTimers|FilePathPair|'
     r'charconv|StringCase|TypeHelpers|FileIO|UserFlags|SpatialFrame|UnitConversion)'),
    ('same', 'The same jobs 5.2.4 does, rewritten', r'.'),
]

def main():
    epa, cplus, ose = sys.argv[1:4]
    commit = sys.argv[4] if len(sys.argv) > 4 else ''
    eng = os.path.join(ose, 'src', 'engine')
    out = dict(
        note='Generated by tools/loc_buckets.py; counting rules in its docstring.',
        swmm6_commit=commit,
        epa524=tally(files(os.path.join(epa, 'src', 'solver'))),
        swmm5cplus=tally(files(os.path.join(cplus, 'src', 'engine'))),
        swmm6_engine=tally(files(eng, skip=('2d',))),
    )
    groups = collections.OrderedDict((k, dict(label=lab, paths=[])) for k, lab, _ in RULES)
    for p in files(eng, skip=('2d',)):
        rel = os.path.relpath(p, eng)
        for k, _, rx in RULES:
            if re.search(rx, rel):
                groups[k]['paths'].append(p)
                break
    out['swmm6_buckets'] = [dict(key=k, label=g['label'], **tally(g['paths'])) for k, g in groups.items()]
    big = sorted(((count(p)[0], os.path.relpath(p, eng)) for p in files(eng, skip=('2d',))), reverse=True)[:12]
    out['swmm6_largest'] = [dict(lines=n, path=r) for n, r in big]

    def part(rel, skip=()):
        return tally(files(os.path.join(ose, rel), skip))
    out['swmm6_outside_engine'] = collections.OrderedDict([
        ('2D surface and subsurface (src/engine/2d)', part('src/engine/2d')),
        ('Carried 5.3.0-beta.3 legacy engine (src/legacy/engine)', part('src/legacy/engine')),
        ('Public headers (include)', part('include')),
        ('Cython-generated C for the legacy Python binding (python/openswmm)', part('python/openswmm')),
        ('Unit tests (tests/unit)', part('tests/unit')),
    ])
    out['epa524_tests'] = tally(files(os.path.join(epa, 'tests')))

    # a few facts the essay quotes
    allsrc = list(files(eng))
    txt = {p: open(p, errors='replace').read() for p in allsrc}
    out['facts'] = dict(
        parity_comments=sum(t.count('PARITY') for t in txt.values()),
        checkpoint_hotstart_lines=sum(count(p)[0] for p in allsrc
                                      if re.search(r'checkpoint|hotstart', os.path.basename(p), re.I)),
        doxygen_tag_lines=sum(len(re.findall(r'(?m)^\s*(?:\*|///|//!)\s*[@\\](?:brief|param|return|note|details|see)\b', t))
                              for p, t in txt.items() if '/2d/' not in p),
        swmm_api_names=len({m for p in files(os.path.join(ose, 'include'))
                            for m in re.findall(r'\bswmm_[a-z0-9_]+(?=\s*\()', open(p, errors='replace').read())}),
        xsect_files_lines=sum(count(os.path.join(eng, 'hydraulics', f))[0] for f in
                              ('XSection.cpp', 'XSectKernels.hpp', 'XSectBatch.cpp', 'XSectBatch.hpp',
                               'XSectLookup.hpp', 'xsect_tables.hpp')),
        epa_xsect_c_lines=count(os.path.join(epa, 'src', 'solver', 'xsect.c'))[0],
        swmmengine_cpp_lines=count(os.path.join(eng, 'core', 'SWMMEngine.cpp'))[0],
    )
    json.dump(out, sys.stdout, indent=1)
    print()

if __name__ == '__main__':
    main()
